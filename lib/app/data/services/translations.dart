class TranslationService extends GetxService {
  final Map<String, Map<String, String>> dynamicKeys = {};

  Future<TranslationService> init() async {
    await _loadCachedTranslations();
    _fetchTranslationsFromSupabase();
    return this;
  }

  Future<void> _loadCachedTranslations() async {
    try {
      final db = Get.find<DatabaseService>();
      final cachedString = db.settingsBox.get('cached_translations');
      if (cachedString != null && cachedString is Map) {
        final Map<String, dynamic> rawMap = Map<String, dynamic>.from(cachedString);
        rawMap.forEach((locale, keys) {
          dynamicKeys[locale] = Map<String, String>.from(keys);
        });
        Get.addTranslations(dynamicKeys);
      }
    } catch (e) {
      
    }
  }

  Future<void> _fetchTranslationsFromSupabase() async {
    try {
      final supabase = Supabase.instance.client;
      final data = await supabase.from('translations').select();
      
      bool updated = false;
      for (final row in data) {
        final locale = row['locale'] as String;
        final key = row['key'] as String;
        final value = row['value'] as String;

        dynamicKeys.putIfAbsent(locale, () => {});
        if (dynamicKeys[locale]![key] != value) {
          dynamicKeys[locale]![key] = value;
          updated = true;
        }
      }

      if (updated) {
        Get.addTranslations(dynamicKeys);
        
        
        final db = Get.find<DatabaseService>();
        await db.settingsBox.put('cached_translations', dynamicKeys);
      }
    } catch (e) {
      
    }
  }
}

